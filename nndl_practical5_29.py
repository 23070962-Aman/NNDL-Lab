# ============================================================
# PRACTICAL 5: TRANSFER LEARNING FOR FLOWER IMAGE CLASSIFICATION
# Pre-trained Model: MobileNetV2
# Dataset: Kaggle Flowers Recognition
# ============================================================

# 1. Import Libraries
import tensorflow as tf
import numpy as np
import matplotlib.pyplot as plt
import zipfile
import os

from google.colab import files
from tensorflow.keras.preprocessing.image import ImageDataGenerator
from tensorflow.keras.applications import MobileNetV2
from tensorflow.keras.layers import Dense, GlobalAveragePooling2D
from tensorflow.keras.models import Model
from tensorflow.keras.utils import load_img, img_to_array

print("TensorFlow Version:", tf.__version__)

# ============================================================
# 2. Upload Kaggle Dataset ZIP
# ============================================================

print("Upload the Flowers Recognition ZIP file downloaded from Kaggle.")

uploaded = files.upload()

zip_file = list(uploaded.keys())[0]

# ============================================================
# 3. Extract Dataset
# ============================================================

with zipfile.ZipFile(zip_file, 'r') as zip_ref:
    zip_ref.extractall('/content/')

print("Dataset extracted successfully.")

# ============================================================
# 4. Find Dataset Folder
# ============================================================

# Kaggle Flowers Recognition dataset normally extracts to:
# /content/flowers

dataset_path = "/content/flowers"

if not os.path.exists(dataset_path):
    print("Dataset folder not found.")
else:
    print("Dataset path:", dataset_path)

# ============================================================
# 5. Image Parameters
# ============================================================

IMG_SIZE = (224, 224)
BATCH_SIZE = 32

# ============================================================
# 6. Image Preprocessing and Train/Validation Split
# ============================================================

datagen = ImageDataGenerator(
    rescale=1./255,
    validation_split=0.2
)

train_data = datagen.flow_from_directory(
    dataset_path,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='categorical',
    subset='training',
    shuffle=True
)

val_data = datagen.flow_from_directory(
    dataset_path,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='categorical',
    subset='validation',
    shuffle=False
)

# ============================================================
# 7. Display Classes
# ============================================================

print("\nFlower Classes:")

for class_name, class_index in train_data.class_indices.items():
    print(class_index, ":", class_name)

# ============================================================
# 8. Load Pre-trained MobileNetV2
# ============================================================

base_model = MobileNetV2(
    weights='imagenet',
    include_top=False,
    input_shape=(224, 224, 3)
)

# Freeze pre-trained layers
base_model.trainable = False

# ============================================================
# 9. Add New Classification Layers
# ============================================================

x = base_model.output

x = GlobalAveragePooling2D()(x)

x = Dense(128, activation='relu')(x)

output = Dense(
    train_data.num_classes,
    activation='softmax'
)(x)

model = Model(
    inputs=base_model.input,
    outputs=output
)

# ============================================================
# 10. Compile Model
# ============================================================

model.compile(
    optimizer='adam',
    loss='categorical_crossentropy',
    metrics=['accuracy']
)

# ============================================================
# 11. Display Model Summary
# ============================================================

model.summary()

# ============================================================
# 12. Train Model
# ============================================================

print("\nStarting Model Training...\n")

history = model.fit(
    train_data,
    validation_data=val_data,
    epochs=5
)

# ============================================================
# 13. Evaluate Model
# ============================================================

loss, accuracy = model.evaluate(val_data)

print("\n==============================")
print("MODEL EVALUATION")
print("==============================")
print("Validation Loss:", round(loss, 4))
print("Validation Accuracy:", round(accuracy * 100, 2), "%")

# ============================================================
# 14. Plot Training and Validation Accuracy
# ============================================================

plt.figure(figsize=(8, 5))

plt.plot(
    history.history['accuracy'],
    label='Training Accuracy'
)

plt.plot(
    history.history['val_accuracy'],
    label='Validation Accuracy'
)

plt.xlabel('Epoch')
plt.ylabel('Accuracy')
plt.title('Training and Validation Accuracy')
plt.legend()
plt.show()

# ============================================================
# 15. Plot Training and Validation Loss
# ============================================================

plt.figure(figsize=(8, 5))

plt.plot(
    history.history['loss'],
    label='Training Loss'
)

plt.plot(
    history.history['val_loss'],
    label='Validation Loss'
)

plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.title('Training and Validation Loss')
plt.legend()
plt.show()

# ============================================================
# 16. Upload New Flower Image for Prediction
# ============================================================

print("\nUpload a flower image for prediction:")

new_image = files.upload()

image_name = list(new_image.keys())[0]

# ============================================================
# 17. Preprocess New Image
# ============================================================

img = load_img(
    image_name,
    target_size=IMG_SIZE
)

img_array = img_to_array(img)

img_array = img_array / 255.0

img_array = np.expand_dims(
    img_array,
    axis=0
)

# ============================================================
# 18. Predict Flower
# ============================================================

prediction = model.predict(img_array)

predicted_class = np.argmax(prediction[0])

class_names = list(train_data.class_indices.keys())

predicted_flower = class_names[predicted_class]

confidence = prediction[0][predicted_class] * 100

# ============================================================
# 19. Display Prediction
# ============================================================

print("\n==============================")
print("FLOWER PREDICTION")
print("==============================")

print("Predicted Flower:", predicted_flower)
print("Confidence:", round(confidence, 2), "%")

# ============================================================
# 20. Display Image
# ============================================================

plt.figure(figsize=(6, 6))

plt.imshow(img)
plt.axis('off')

plt.title(
    f"Predicted: {predicted_flower}\n"
    f"Confidence: {confidence:.2f}%"
)

plt.show()



