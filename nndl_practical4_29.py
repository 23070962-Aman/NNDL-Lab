import tensorflow as tf
import numpy as np
import matplotlib.pyplot as plt

from tensorflow.keras.datasets import cifar10
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense, Flatten, Conv2D, MaxPooling2D
# from tensorflow.keras.losses import sparse_categorical_crossentropy
from tensorflow.keras.optimizers import Adam

(X_train, y_train), (X_test, y_test) = cifar10.load_data()

print("Training Image: ",X_train.shape)
print("Testing Image: ",X_test.shape)

class_name =  ['Airplane','Automobile','Bird','Cat','Deer','Dog','Frog','Horse','Ship','Truck']

plt.imshow(X_train[0])
plt.title(class_name[y_train[0][0]])
plt.axis("off")
plt.show()

# normalize dataset
X_train = X_train.astype('float32') / 255.0
X_test = X_test.astype('float32') / 255.0

#create CNN model
model = Sequential()
model.add(Conv2D(32, (3,3), activation='relu', input_shape=(32,32,3))) # Corrected input_shape for CIFAR-10 (3 color channels)
model.add(MaxPooling2D((2,2)))
model.add(Conv2D(64, (3,3), activation='relu'))
model.add(MaxPooling2D((2,2)))
model.add(Flatten())
model.add(Dense(64, activation='relu'))
model.add(Dense(10, activation='softmax'))

#compile the model
model.compile(
    optimizer=Adam(learning_rate=0.001),
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

#train model
history= model.fit(X_train, y_train, epochs = 10, batch_size = 64, validation_split = 0.2)

#make prediction
prediction = model.predict(X_test)
predicted_class = np.argmax(prediction, axis=1)

#accuracy
loss, accuracy = model.evaluate(X_test, y_test)
print("Loss: ", loss)
print("Accuracy: ", accuracy)

#display prediction
print("predicted class")
print(class_name[predicted_class[0]])
print()
print("actual class")
print(class_name[y_test[0][0]])

#plot accuracy graph
plt.plot(history.history['accuracy'], label='accuracy')
plt.plot(history.history['val_accuracy'], label = 'val_accuracy')
plt.title("Model Accuracy")
plt.xlabel('Epoch')
plt.ylabel('Accuracy')
plt.legend(["training","Validation"])
plt.show()

# LOSS graph
plt.plot(history.history['loss'])
plt.plot(history.history['val_loss'])
plt.title("Model Loss")
plt.xlabel('Epoch')
plt.ylabel('Loss')
plt.legend(["training","Validation"])
plt.show()

