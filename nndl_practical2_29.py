import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import Perceptron
from sklearn.metrics import accuracy_score, confusion_matrix, classification_report

iris = load_iris()

X = iris.data
y = iris.target

print("Feature names:", iris.feature_names)
print("Target names:", iris.target_names)
print("Dataset shape:", X.shape)

# Select Setosa (0) and Versicolor (1)
mask = y < 2

X_binary = X[mask]
y_binary = y[mask]

print("Binary dataset shape:", X_binary.shape)
print("Classes:", np.unique(y_binary))

X_train, X_test, y_train, y_test = train_test_split(
    X_binary,
    y_binary,
    test_size=0.2,
    random_state=42,
    stratify=y_binary
)

print("Training samples:", X_train.shape[0])
print("Testing samples:", X_test.shape[0])

scaler = StandardScaler()

X_train = scaler.fit_transform(X_train)
X_test = scaler.transform(X_test)

perceptron = Perceptron(
    max_iter=1000,
    eta0=0.1,
    random_state=42
)

perceptron.fit(X_train, y_train)

print("Perceptron model trained successfully.")

y_pred = perceptron.predict(X_test)

print("Predicted values:")
print(y_pred)

print("\nActual values:")
print(y_test)

accuracy = accuracy_score(y_test, y_pred)

print("Accuracy:", accuracy)
print("Accuracy (%):", accuracy * 100)

cm = confusion_matrix(y_test, y_pred)

print("Confusion Matrix:")
print(cm)

print(classification_report(
    y_test,
    y_pred,
    target_names=["Setosa", "Versicolor"]
))

new_flower = [[5.1, 3.5, 1.4, 0.2]]

# Scale the input
new_flower_scaled = scaler.transform(new_flower)

prediction = perceptron.predict(new_flower_scaled)

if prediction[0] == 0:
    print("Predicted class: Setosa")
else:
    print("Predicted class: Versicolor")